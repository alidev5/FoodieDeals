import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { build, type Plugin } from "esbuild";

import { EDGE_FUNCTION_FILE } from "./paths";

const apiDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(join(apiDir, "package.json"));

// Third-party packages stay external as `npm:` specifiers, pinned to the versions installed here,
// so Supabase's Deno runtime fetches exactly what the tests ran against.
const NPM_PACKAGES = ["hono", "postgres", "stripe", "zod"];

function installedVersion(name: string): string {
  let dir = dirname(require.resolve(name));
  for (;;) {
    try {
      const manifest = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
      if (manifest.name === name) return manifest.version;
    } catch {
      // Keep walking up until the package root.
    }
    const parent = dirname(dir);
    if (parent === dir) throw new Error(`Could not find the installed version of ${name}`);
    dir = parent;
  }
}

const npmSpecifiers: Plugin = {
  name: "npm-specifiers",
  setup(pluginBuild) {
    const versions = new Map(NPM_PACKAGES.map((name) => [name, installedVersion(name)]));
    pluginBuild.onResolve({ filter: /^[a-z@]/ }, (args) => {
      const name = NPM_PACKAGES.find((pkg) => args.path === pkg || args.path.startsWith(`${pkg}/`));
      if (!name) return undefined;
      return {
        path: `npm:${name}@${versions.get(name)}${args.path.slice(name.length)}`,
        external: true,
      };
    });
  },
};

await build({
  entryPoints: [join(apiDir, "src", "edge.ts")],
  outfile: EDGE_FUNCTION_FILE,
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  mainFields: ["module", "main"],
  plugins: [npmSpecifiers],
  banner: {
    js: "// Generated by `pnpm --filter api bundle` from apps/api/src. Do not edit by hand.",
  },
  logLevel: "info",
});
